#!/usr/bin/env python3
"""Emit paper/generated/contract-macros.tex from contracts/tdl-contract-v1.json.

The paper prints the headline operating point, its thresholds, the byte grid,
the seed design and the bootstrap plan through these macros, so none of them is
typed into a .tex source. ``--check`` regenerates the file and also refuses any
public surface that disagrees with the contract's headline operating point:

- paper/generated/headline-results.json ``thresholds`` and ``metric_name``
  (the claims renderer's input);
- the \\TdlTransferThreshold, \\TdlDriverThreshold and \\TdlMetricName macros in
  paper/generated/headline-macros.tex;
- the README's ``KiB@<operating point>`` form and its threshold wording.

Run from the repository root:
    python3 -B paper/scripts/contract_macros.py           # write
    python3 -B paper/scripts/contract_macros.py --check   # verify, write nothing
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "contracts" / "tdl-contract-v1.json"
OUTPUT = ROOT / "paper" / "generated" / "contract-macros.tex"
RESULTS = ROOT / "paper" / "generated" / "headline-results.json"
HEADLINE_MACROS = ROOT / "paper" / "generated" / "headline-macros.tex"
README = ROOT / "README.md"

# README states the headline thresholds in words; a contract change must update both.
THRESHOLD_WORDS = {0.8: "four-fifths", 0.9: "nine-tenths", 0.95: "nineteen-twentieths"}
COUNT_WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven",
               8: "eight", 9: "nine", 10: "ten"}


class ContractMismatch(ValueError):
    """A public surface disagrees with the TDL contract."""


def headline_point(contract: dict) -> dict:
    points = [point for point in contract["operating_points"] if point.get("headline") is True]
    if len(points) != 1:
        raise ContractMismatch("contract must mark exactly one headline operating point")
    point = points[0]
    if point["id"] != contract["headline_operating_point"]:
        raise ContractMismatch("headline_operating_point does not name the headline operating point")
    return point


def kib(value: float) -> str:
    return f"{value:g}"


def render(contract: dict) -> str:
    point = headline_point(contract)
    grid = [kib(value) for value in contract["byte_grid_kib"]]
    grid_text = ", ".join(grid[:-1]) + " and " + grid[-1] + "~KiB" if len(grid) > 1 else grid[0] + "~KiB"
    seeds = contract["seed_policy"]
    aggregation = contract["aggregation_policy"]
    drivers = contract["driver_protocol"]
    level = round(100 * (1 - aggregation["alpha"]))
    frozen = "frozen" if contract["protocol_frozen"] else "draft (unfrozen)"
    lines = [
        "% Generated by paper/scripts/contract_macros.py from contracts/tdl-contract-v1.json. Do not edit.",
        f"\\newcommand{{\\MetricName}}{{{contract['metric_name']}}}",
        f"\\newcommand{{\\ContractId}}{{{contract['contract_id']}}}",
        f"\\newcommand{{\\ContractState}}{{{frozen}}}",
        f"\\newcommand{{\\HeadlinePoint}}{{{point['id']}}}",
        f"\\newcommand{{\\TauT}}{{{point['transfer_threshold']:.2f}}}",
        f"\\newcommand{{\\TauD}}{{{point['driver_threshold']:.2f}}}",
        f"\\newcommand{{\\ByteGrid}}{{{grid_text}}}",
        f"\\newcommand{{\\SeedDesign}}{{{COUNT_WORDS.get(seeds['fit_seeds_count'], seeds['fit_seeds_count'])} "
        f"generator fit seeds by {COUNT_WORDS.get(seeds['sample_seeds_count'], seeds['sample_seeds_count'])} "
        "sample seeds}",
        f"\\newcommand{{\\BootstrapReplicates}}{{{aggregation['bootstrap_replicates']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\BootstrapSeed}}{{{aggregation['bootstrap_seed']}}}",
        f"\\newcommand{{\\LowerBoundLevel}}{{{level}\\%}}",
        f"\\newcommand{{\\StabilityFloor}}{{{drivers['stability_floor']:.2f}}}",
    ]
    return "\n".join(lines) + "\n"


def macro_values(text: str) -> dict[str, str]:
    return {name: value for name, value in re.findall(r"\\newcommand\{\\([A-Za-z]+)\}\{([^{}]*)\}", text)}


def surface_failures(contract: dict, results: dict, headline_macros: str | None, readme: str) -> list[str]:
    point = headline_point(contract)
    failures = []
    thresholds = results.get("thresholds", {})
    if thresholds.get("transfer") != point["transfer_threshold"]:
        failures.append(f"headline-results.json transfer threshold {thresholds.get('transfer')!r} "
                        f"!= contract {point['transfer_threshold']!r}")
    if thresholds.get("drivers") != point["driver_threshold"]:
        failures.append(f"headline-results.json driver threshold {thresholds.get('drivers')!r} "
                        f"!= contract {point['driver_threshold']!r}")
    if results.get("metric_name") != contract["metric_name"]:
        failures.append("headline-results.json metric_name differs from the contract")
    if headline_macros is not None:
        values = macro_values(headline_macros)
        expected = {"TdlTransferThreshold": f"{point['transfer_threshold']:.2f}",
                    "TdlDriverThreshold": f"{point['driver_threshold']:.2f}",
                    "TdlMetricName": contract["metric_name"]}
        for name, value in expected.items():
            if values.get(name) != value:
                failures.append(f"headline-macros.tex \\{name} is {values.get(name)!r}, contract gives {value!r}")
    transfer_label, driver_label = point["id"].split("/")
    if f"`KiB@{point['id']}`" not in readme:
        failures.append(f"README does not state the public form `KiB@{point['id']}`")
    for label, value in ((transfer_label, point["transfer_threshold"]), (driver_label, point["driver_threshold"])):
        word = THRESHOLD_WORDS.get(value)
        if word is None:
            failures.append(f"no README wording for threshold {value!r}; extend THRESHOLD_WORDS and the README")
        elif f"{word}" not in readme or f"({label})" not in readme:
            failures.append(f"README does not state the {label} threshold as '{word} ... ({label})'")
    return failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify the committed file and public surfaces")
    args = parser.parse_args(argv)
    contract = json.loads(CONTRACT.read_text())
    expected = render(contract)
    if not args.check:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print("wrote", OUTPUT.relative_to(ROOT))
        return 0
    failures = []
    if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
        failures.append(f"{OUTPUT.relative_to(ROOT)} differs from the contract; run paper/scripts/contract_macros.py")
    headline_macros = HEADLINE_MACROS.read_text() if HEADLINE_MACROS.is_file() else None
    failures += surface_failures(contract, json.loads(RESULTS.read_text()), headline_macros, README.read_text())
    for failure in failures:
        print("contract macros:", failure, file=sys.stderr)
    if not failures:
        print("contract macros match", CONTRACT.relative_to(ROOT), "headline", headline_point(contract)["id"])
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
