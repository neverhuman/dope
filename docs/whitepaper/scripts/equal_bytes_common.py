def fmt(value: float, digits: int = 2) -> str:
    text = f"{value:,.{digits}f}"
    return text[1:] if text.startswith("-") and float(text.replace(",", "")) == 0 else text


def human_bytes(value: float) -> str:
    for unit, scale in (("GB", 1e9), ("MB", 1e6), ("KB", 1e3)):
        if value >= scale:
            return f"{value / scale:,.1f}~{unit}"
    return f"{value:,.0f}~B"


def latex_table(header: list[str], rows: list[list[str]], align: str) -> str:
    lines = [f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    lines += [" & ".join(row) + " \\\\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}"]
    return f"% {GENERATED_NOTE}; do not edit.\n" + "\n".join(lines) + "\n"


def coverage(per_lineage: list[list[dict]], threshold: float, budgets) -> list[float]:
    """Share of lineages with a configuration within the budget that reaches the threshold."""
    return [float(np.mean([any(p["bytes"] is not None and p["bytes"] <= budget and p["robust"] is not None
                               and p["robust"] >= threshold for p in points) for points in per_lineage]))
            for budget in budgets]
